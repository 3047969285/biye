def insert_after(p: Paragraph, text: str):
    new_p=deepcopy(p._p)
    for child in list(new_p): new_p.remove(child)
    p._p.addnext(new_p)
    np=Paragraph(new_p,p._parent); np.style='Normal'; np.add_run(text); return np

def find_start(doc,prefix):
    for p in doc.paragraphs:
        if p.text.strip().startswith(prefix): return p
    raise ValueError(prefix)

def insert_many(p,texts):
    cur=p
    for t in texts: cur=insert_after(cur,t)

